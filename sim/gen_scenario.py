#!/usr/bin/env python3
"""Write the Stonefish scenarios (clear / turbid water) and scenarios/trajectory_meta.json.

XML syntax is taken from: stonefish/docs/{scenario,environment,materials,animated,sensors,actuators}.rst
(environment, ocean, looks, static model, animated body, trajectory keypoints, sensors, lights) and
stonefish_ros2/src/stonefish_ros2/ROS2ScenarioParser.cpp (<ros_publisher topic=...> for sensors and for animated
bodies; camera topics get /image_color and /camera_info appended). The vehicle is an animated body (pwl trajectory)
so its motion is exact and repeatable; sensors are attached to it without a <link> tag (link names are for robots).

  python3 gen_scenario.py [--lights]
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

import rig
import trajectory as tj

HERE = Path(__file__).resolve().parent
TOPICS = {
    "cam_left": "/sim/cam_left",  # + /image_color (rgb8), /camera_info
    "cam_right": "/sim/cam_right",
    "imu": "/sim/imu_sf",  # sensor_msgs/Imu (diagnostic; the benchmark IMU is synthesised from the trajectory)
    "pressure": "/sim/pressure",  # sensor_msgs/FluidPressure [Pa gauge]
    "dvl": "/sim/dvl",  # stonefish_ros2/DVL
    "gt_odom": "/sim/gt_odom",  # nav_msgs/Odometry, world_ned, 50 Hz
    "traj_state": "/sim/traj_state",  # nav_msgs/Odometry of the animated body, every physics step (time reference)
}
VARIANTS = {
    # jerlov: 0.0 = Jerlov type I ... 1.0 = type 9C (stonefish/docs/environment.rst "Ocean optics")
    "clear": {"jerlov": 0.10, "particles": "false"},
    "turbid": {"jerlov": 0.55, "particles": "true"},
}


def f(v, digits: int = 6) -> str:
    return " ".join(f"{x:.{digits}f}" for x in np.atleast_1d(v))


def origin(T: np.ndarray) -> str:
    r, p, y = rig.rpy_from_rot(T[:3, :3])
    return f'<origin xyz="{f(T[:3, 3], 9)}" rpy="{f([r, p, y], 9)}"/>'


def keypoint_xml(traj: tj.Trajectory) -> str:
    t, p, e = traj.keypoints()
    return "\n".join(f'            <keypoint time="{ti:.4f}" xyz="{f(pi)}" rpy="{f(ei)}"/>' for ti, pi, ei in zip(t, p, e))


def scenario_xml(variant: str, traj: tj.Trajectory, lights: bool, cam_rate_hz: float = rig.CAM_RATE_HZ) -> str:
    v = VARIANTS[variant]
    r = rig.build_rig()
    fx = rig.intrinsics()[0]
    light = ""
    if lights:  # not verified: the animated-body parser may not read <light> (see README)
        light = (f'        <light name="VehicleLight">\n            <specs radius="0.05" cone_angle="60.0" illuminance="3000.0"/>\n'
                 f'            <color temperature="5600.0"/>\n            {origin(r.T_B_C0)}\n        </light>\n')
    return f"""<?xml version="1.0"?>
<!-- Generated by sim/gen_scenario.py ({variant}); do not edit by hand. Frames: see sim/rig.py and sim/README.md.
     Camera fx = fy = {fx:.4f} px from horizontal_fov {rig.HFOV_DEG} deg at {rig.IMG_W}x{rig.IMG_H}. -->
<scenario>
    <environment>
        <ned latitude="40.0" longitude="3.0"/>
        <ocean>
            <water density="{rig.WATER_DENSITY_KGPM3:.1f}" jerlov="{v['jerlov']}"/>
            <waves height="0.0"/>
            <particles enabled="{v['particles']}"/>
        </ocean>
        <atmosphere>
            <sun azimuth="120.0" elevation="50.0"/>
        </atmosphere>
    </environment>

    <materials>
        <material name="Rock" density="3000.0" restitution="0.5"/>
        <friction_table>
            <friction material1="Rock" material2="Rock" static="0.9" dynamic="0.7"/>
        </friction_table>
    </materials>

    <looks>
        <look name="seabed" gray="1.0" roughness="0.9" texture="assets/seabed_tex.png"/>
        <look name="rock" gray="1.0" roughness="0.8" texture="assets/rock_tex.png"/>
        <look name="metal" gray="1.0" roughness="0.5" metalness="0.2" texture="assets/metal_tex.png"/>
        <look name="vehicle" rgb="0.9 0.5 0.0" roughness="0.4"/>
    </looks>

    <static name="Seabed" type="model">
        <physical>
            <mesh filename="assets/terrain.obj" scale="1.0"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        </physical>
        <visual>
            <mesh filename="assets/terrain.obj" scale="1.0"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        </visual>
        <material name="Rock"/>
        <look name="seabed"/>
        <world_transform xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
    </static>

    <static name="Structures" type="model">
        <physical>
            <mesh filename="assets/structures.obj" scale="1.0"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        </physical>
        <visual>
            <mesh filename="assets/structures.obj" scale="1.0"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        </visual>
        <material name="Rock"/>
        <look name="metal"/>
        <world_transform xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
    </static>

    <static name="Rocks" type="model">
        <physical>
            <mesh filename="assets/rocks.obj" scale="1.0"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        </physical>
        <visual>
            <mesh filename="assets/rocks.obj" scale="1.0"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        </visual>
        <material name="Rock"/>
        <look name="rock"/>
        <world_transform xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
    </static>

    <animated name="Vehicle" type="box" collisions="false">
        <dimensions xyz="0.16 0.16 0.10"/>
        <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
        <material name="Rock"/>
        <look name="vehicle"/>
        <trajectory type="pwl" playback="onetime">
{keypoint_xml(traj)}
        </trajectory>
        <ros_publisher topic="{TOPICS['traj_state']}"/>

        <sensor name="CamLeft" rate="{cam_rate_hz}" type="camera">
            <specs resolution_x="{rig.IMG_W}" resolution_y="{rig.IMG_H}" horizontal_fov="{rig.HFOV_DEG}"/>
            {origin(r.T_B_C0)}
            <ros_publisher topic="{TOPICS['cam_left']}"/>
        </sensor>

        <sensor name="CamRight" rate="{cam_rate_hz}" type="camera">
            <specs resolution_x="{rig.IMG_W}" resolution_y="{rig.IMG_H}" horizontal_fov="{rig.HFOV_DEG}"/>
            {origin(r.T_B_C1)}
            <ros_publisher topic="{TOPICS['cam_right']}"/>
        </sensor>

        <sensor name="IMU" rate="{rig.IMU_RATE_HZ}" type="imu">
            <range angular_velocity="10.0 10.0 10.0" linear_acceleration="100.0"/>
            <noise angle="0.0017" angular_velocity="{rig.GYR_NOISE_DENSITY * rig.IMU_RATE_HZ ** 0.5:.6f}" yaw_drift="0.0" linear_acceleration="{rig.ACC_NOISE_DENSITY * rig.IMU_RATE_HZ ** 0.5:.6f}"/>
            <history samples="1"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
            <ros_publisher topic="{TOPICS['imu']}"/>
        </sensor>

        <sensor name="Pressure" rate="{rig.PRESSURE_RATE_HZ}" type="pressure">
            <range pressure="{rig.PRESSURE_RANGE_PA:.1f}"/>
            <noise pressure="{rig.PRESSURE_NOISE_PA}"/>
            <history samples="1"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
            <ros_publisher topic="{TOPICS['pressure']}"/>
        </sensor>

        <sensor name="DVL" rate="{rig.DVL_RATE_HZ}" type="dvl">
            <specs beam_angle="{rig.DVL_BEAM_ANGLE_DEG}"/>
            <range velocity="{rig.DVL_VEL_MAX_MPS} {rig.DVL_VEL_MAX_MPS} {rig.DVL_VEL_MAX_MPS}" altitude_min="{rig.DVL_ALT_MIN_M}" altitude_max="{rig.DVL_ALT_MAX_M}"/>
            <water_layer minimum_layer_size="2.0" boundary_near="3.0" boundary_far="9.0"/>
            <noise velocity_percent="{rig.DVL_NOISE_VEL_PERCENT}" velocity="{rig.DVL_NOISE_VEL_MPS}" altitude="{rig.DVL_NOISE_ALT_M}" water_velocity_percent="0.1" water_velocity="0.1"/>
            <history samples="1"/>
            {origin(r.T_B_D)}
            <ros_publisher topic="{TOPICS['dvl']}"/>
        </sensor>

        <sensor name="GTOdom" rate="{rig.GT_ODOM_RATE_HZ}" type="odometry">
            <history samples="1"/>
            <origin xyz="0.0 0.0 0.0" rpy="0.0 0.0 0.0"/>
            <ros_publisher topic="{TOPICS['gt_odom']}"/>
        </sensor>
{light}    </animated>
</scenario>
"""


def trajectory_meta(traj: tj.Trajectory, cam_rate_hz: float = rig.CAM_RATE_HZ) -> dict:
    ts = np.arange(0.0, traj.duration_s, 1.0 / rig.DVL_RATE_HZ)
    exp = {}
    for name, az in (("beams_45_135_225_315", rig.DVL_BEAM_AZIMUTHS_DEG), ("beams_0_90_180_270", (0.0, 90.0, 180.0, 270.0))):
        valid, _, _ = tj.dvl_expected(traj, ts, azimuths_deg=az)
        exp[name] = [[round(a, 2), round(b, 2)] for a, b in tj.invalid_intervals(ts, valid)]
    leg2 = traj.t[traj.seg == 3]
    t_mid = 0.5 * (leg2[0] + leg2[-1])
    t, p, e = traj.keypoints()
    digest = hashlib.sha256(np.round(np.column_stack([t, p, e]), 6).tobytes()).hexdigest()
    return {
        "duration_s": round(traj.duration_s, 3),
        "record_s": round(traj.duration_s + 2.0, 1),
        "sim_rate_hz": rig.SIM_RATE_HZ,
        "cam_rate_hz": cam_rate_hz,
        "keypoint_rate_hz": rig.KEYPOINT_RATE_HZ,
        "keypoint_sha256": digest,
        "expected_dvl_lock_loss_s": exp,
        "suggested_blackout": f"{t_mid - 10.0:.0f}:20",
        "blackout_note": "t0:dur [s after the first image], in the middle of leg 2 (DVL valid), 20 s",
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lights", action="store_true", help="attach a spot light to the vehicle (unverified syntax)")
    ap.add_argument("--cam-rate", type=float, default=rig.CAM_RATE_HZ, help="camera rate [Hz]; lower it to cut render cost")
    ap.add_argument("--out", type=Path, default=HERE / "scenarios")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    traj = tj.build_trajectory()
    for variant in VARIANTS:
        (a.out / f"seabed_{variant}.scn").write_text(scenario_xml(variant, traj, a.lights, a.cam_rate))
    meta = trajectory_meta(traj, a.cam_rate)
    (a.out / "trajectory_meta.json").write_text(json.dumps(meta, indent=1) + "\n")
    print(json.dumps(meta, indent=1))


if __name__ == "__main__":
    main()
